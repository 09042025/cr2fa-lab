const BY_CODE = new Map(LANGS.map((l) => [l.code.toLowerCase(), l]));
export const langByCode = (code: string | null | undefined): Lang => BY_CODE.get((code ?? "").toLowerCase()) ?? LANGS[0];

/** Lê o idioma escolhido no cookie do Google Tradutor ("/pt/en" → "en"). Sem cookie, é o original. */
export function langFromCookie(cookie: string): string {
  const m = /(?:^|;\s*)googtrans=\/[^/;]+\/([A-Za-z-]+)/.exec(cookie);
  return m && BY_CODE.has(m[1].toLowerCase()) ? langByCode(m[1]).code : SOURCE_LANG;
}

